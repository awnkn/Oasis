function toCountry([code, name, dial, min, max]: Entry): PhoneCountry {
  return { code, name, flag: flagOf(code), dial, min, max };
}

export const ARAB_COUNTRIES: PhoneCountry[] = ARAB.map(toCountry);
export const OTHER_COUNTRIES: PhoneCountry[] = WORLD.map(toCountry);
export const PHONE_COUNTRIES: PhoneCountry[] = [
  ...ARAB_COUNTRIES,
  ...OTHER_COUNTRIES,
];

export const DEFAULT_PHONE_COUNTRY = "JO";

/** Keep digits only, drop a leading zero (local dialing prefix), cap length. */
export function normalizeNationalNumber(
  raw: string,
  country: PhoneCountry
): string {
  return raw.replace(/\D/g, "").replace(/^0+/, "").slice(0, country.max);
}
