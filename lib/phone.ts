// Country calling codes for the booking form. Arab countries are listed
// first (Jordan is the default), then the rest of the world. `min`/`max`
// bound the national number length (digits after the country code, leading
// zero stripped) — approximate for smaller countries, exact for the region.

export interface PhoneCountry {
  code: string;
  name: string;
  flag: string;
  dial: string;
  min: number;
  max: number;
}

type Entry = [code: string, name: string, dial: string, min: number, max: number];

/** Emoji flag from a 2-letter ISO code. */
function flagOf(code: string): string {
  return String.fromCodePoint(
    ...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)
  );
}

